/**
 * Writes packages/core/src/viz/worldTable.generated.ts from the vendored
 * world outlines: the name → ISO code table and every country's centroid.
 *
 * Run from the repo root: `npm run world:generate`.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deriveWorldTable } from "./derive.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE = "apps/web/src/features/visualize/assets/world-countries.geojson";
const OUT = "packages/core/src/viz/worldTable.generated.ts";

const table = deriveWorldTable(
	JSON.parse(readFileSync(join(ROOT, SOURCE), "utf8")),
);

writeFileSync(
	join(ROOT, OUT),
	`// Generated by scripts/world/generate.ts from ${SOURCE}. Do not edit.

/** Natural Earth 110m feature name → ISO 3166-1 alpha-2, for every outline. */
export const WORLD_NAME_TO_CODE: Readonly<Record<string, string>> = ${JSON.stringify(table.nameToCode)};

/** Country centroids \`[lat, lon]\` for every ISO 3166-1 alpha-2 code and XK. */
export const COUNTRY_CENTROIDS: Readonly<
	Record<string, readonly [number, number]>
> = ${JSON.stringify(table.centroids)};
`,
);
